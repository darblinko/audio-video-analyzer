import React, { useEffect, useState } from 'react';
import { analyzeSample, getSamples } from './api';

function SamplePicker({ onUploadComplete, onError }) {
  const [samples, setSamples] = useState([]);
  const [pending, setPending] = useState(null);

  useEffect(() => {
    getSamples()
      .then((body) => setSamples(body.samples))
      .catch((error) => onError(`Could not load samples: ${error.message}`));
  }, [onError]);

  const analyze = async (sampleId) => {
    setPending(sampleId);
    try {
      const result = await analyzeSample(sampleId);
      onUploadComplete(result.analysis_id);
    } catch (error) {
      onError(`Sample analysis failed: ${error.message}`);
    } finally {
      setPending(null);
    }
  };

  return (
    <div className="sample-picker">
      <h2>Synthetic sample clips</h2>
      <p className="info-text">
        Generated by scripts/make_samples.py with a fixed seed. No microphone, camera or API key is
        needed.
      </p>
      <ul className="sample-list">
        {samples.map((sample) => (
          <li key={sample.id} className="sample-item">
            <div>
              <strong>{sample.title}</strong>
              <p>{sample.description}</p>
              <audio controls preload="none" src={`/api/samples/${sample.id}/audio`} />
            </div>
            <button
              className="btn btn-primary btn-sm"
              onClick={() => analyze(sample.id)}
              disabled={pending !== null}
            >
              {pending === sample.id ? 'Starting' : 'Analyze'}
            </button>
          </li>
        ))}
      </ul>
    </div>
  );
}

export default SamplePicker;
